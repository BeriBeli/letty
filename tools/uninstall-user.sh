#!/bin/bash
# Remove versioned application files only; retain configuration and session data.
set -euo pipefail

# Read the full function before removing the version containing this script.
main() {
  if [[ $# -gt 1 || ${1:-} == --help || ${1:-} == -h ]]; then
    printf 'Usage: %s [install-directory]\nDefault: ~/.local/share/letty\nKeeps configuration and session data. Close Letty before uninstalling.\n' "$0"
    [[ $# -le 1 ]]
    return
  fi
  local prefix=${1:-"$HOME/.local/share/letty"}
  local launcher="$HOME/.local/bin/letty"
  local entry name package_id link target
  if [[ ! -e "$prefix" && ! -L "$prefix" ]]; then
    printf 'Not installed: %s\n' "$prefix"
    return
  fi
  if [[ ! -d "$prefix" || -L "$prefix" ]]; then
    echo 'Install directory must be a real directory' >&2
    return 1
  fi
  prefix=$(cd -- "$prefix" && pwd)
  if [[ ! -d "$prefix/versions" || -L "$prefix/versions" ]]; then
    echo 'No versioned installation found; refusing removal' >&2
    return 1
  fi

  # Validate the entire installation before deleting any files. Unknown entries
  # in the install root are retained; unknown version entries stop removal.
  shopt -s nullglob dotglob
  for entry in "$prefix/versions/"*; do
    name=${entry##*/}
    if [[ ! "$name" =~ ^[A-Za-z0-9._-]+$ || ! -d "$entry" || -L "$entry" ||
          ! -f "$entry/build-info.json" || -L "$entry/build-info.json" ||
          ! -f "$entry/bin/letty" || -L "$entry/bin/letty" ]]; then
      printf 'Unrecognized version; refusing removal: %s\n' "$entry" >&2
      return 1
    fi
    package_id=$(awk -F'"' '/"package_id"/ {print $4; exit}' "$entry/build-info.json")
    if [[ "$package_id" != "$name" ]]; then
      printf 'Package id mismatch; refusing removal: %s\n' "$entry" >&2
      return 1
    fi
  done
  for link in current previous; do
    if [[ -L "$prefix/$link" ]]; then
      target=$(readlink "$prefix/$link")
      if [[ ! "$target" =~ ^versions/[A-Za-z0-9._-]+$ ||
            "$target" == versions/. || "$target" == versions/.. ||
            ! -d "$prefix/$target" || -L "$prefix/$target" ]]; then
        printf 'Invalid %s link; refusing removal\n' "$link" >&2
        return 1
      fi
    elif [[ -e "$prefix/$link" ]]; then
      printf '%s is not a symlink; refusing removal\n' "$link" >&2
      return 1
    fi
  done

  if [[ -L "$launcher" && $(readlink "$launcher") == "$prefix/current/bin/letty" ]]; then
    rm -- "$launcher"
  fi
  local data_dir=${XDG_DATA_HOME:-"$HOME/.local/share"}
  [[ "$data_dir" == /* ]] || data_dir="$HOME/.local/share"
  local desktop="$data_dir/applications/letty.desktop"
  if [[ -L "$desktop" && $(readlink "$desktop") == "$prefix/letty.desktop" ]]; then
    rm -- "$desktop"
    if command -v update-desktop-database >/dev/null 2>&1; then
      update-desktop-database "$data_dir/applications" || true
    fi
  fi
  if [[ -f "$prefix/letty.desktop" && ! -L "$prefix/letty.desktop" ]] &&
     head -n 1 "$prefix/letty.desktop" | grep -qxF '# Generated by Letty install-user.sh'; then
    rm -- "$prefix/letty.desktop"
  fi
  for link in current previous; do
    if [[ -L "$prefix/$link" ]]; then rm -- "$prefix/$link"; fi
  done
  for entry in "$prefix/versions/"*; do rm -rf -- "$entry"; done
  rmdir -- "$prefix/versions"
  if ! rmdir -- "$prefix" 2>/dev/null; then
    printf 'Kept other files in %s\n' "$prefix"
  fi
  printf 'Uninstalled %s\nConfiguration and session data were kept.\n' "$prefix"
}

main "$@"
