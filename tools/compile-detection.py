#!/usr/bin/env python3
"""Compile the pinned Kero/Herdr regex catalog to bounded Zig NFA data.

Python is a build-time parser only. Letty executes the generated bytecode in Zig;
no Python, Go, regex library or process is needed by detection at runtime.
"""
import hashlib, json, pathlib, re, unicodedata
from re import _parser as parser, _constants as constants
ROOT=pathlib.Path(__file__).resolve().parents[1]

def ranges(values):
    result=[]
    for cp in sorted(set(values)):
        if result and cp==result[-1][1]+1: result[-1][1]=cp
        else: result.append([cp,cp])
    return result

def fold(cp):
    text=chr(cp).casefold()
    return ord(text) if len(text)==1 else cp

def compile_pattern(pattern):
    pattern=re.sub(r'\\[xu]\{([0-9a-fA-F]+)\}',lambda m:'\\U%08x'%int(m[1],16),pattern).replace(r'\z',r'\Z')
    if r'\p{Alphabetic}' in pattern:
        # Kero translates Rust Alphabetic to Go's \pL.
        letters=ranges(cp for cp in range(0x110000) if unicodedata.category(chr(cp)).startswith('L'))
        pattern=pattern.replace(r'\p{Alphabetic}','['+''.join('\\U%08x-\\U%08x'%tuple(pair) for pair in letters)+']')
    parsed=parser.parse(pattern,0); flags=parsed.state.flags
    insensitive=bool(flags&constants.SRE_FLAG_IGNORECASE)
    inst=[]
    def emit(op,**fields):
        if len(inst)>=4096:raise ValueError('regex instruction budget')
        inst.append(dict(op=op,**fields));return len(inst)-1
    def category(value):
        return {'CATEGORY_DIGIT':'digit','CATEGORY_NOT_DIGIT':'not_digit','CATEGORY_SPACE':'space','CATEGORY_NOT_SPACE':'not_space','CATEGORY_WORD':'word','CATEGORY_NOT_WORD':'not_word'}[str(value)]
    def seq(tokens,cont):
        for op,arg in reversed(list(tokens)):
            name=str(op)
            if name=='LITERAL':cont=emit('char',cp=fold(arg) if insensitive else arg,next=cont)
            elif name=='NOT_LITERAL':cont=emit('class',ranges=[[fold(arg) if insensitive else arg]*2],invert=True,next=cont)
            elif name=='ANY':cont=emit('any',next=cont)
            elif name=='IN':
                values=[]; categories=[]; invert=False
                for kind,value in arg:
                    kind=str(kind)
                    if kind=='NEGATE':invert=True
                    elif kind=='LITERAL':values.append(value)
                    elif kind=='RANGE':values.extend(range(value[0],value[1]+1))
                    elif kind=='CATEGORY':categories.append(category(value))
                    else:raise ValueError((kind,value))
                if insensitive:values=[fold(cp) for cp in values]
                cont=emit('class',ranges=ranges(values),categories=categories,invert=invert,next=cont)
            elif name=='CATEGORY':cont=emit('class',categories=[category(arg)],next=cont)
            elif name=='SUBPATTERN':
                if arg[1] or arg[2]:raise ValueError('scoped flags need explicit implementation')
                cont=seq(arg[3],cont)
            elif name=='BRANCH':
                branches=[seq(branch,cont) for branch in arg[1]]
                cont=branches[-1]
                for branch in reversed(branches[:-1]):cont=emit('split',next=branch,other=cont)
            elif name in ('MAX_REPEAT','MIN_REPEAT'):
                minimum,maximum,body=arg
                if minimum>100 or (maximum!=constants.MAXREPEAT and maximum>100):raise ValueError('repeat budget')
                if maximum==constants.MAXREPEAT:
                    loop=emit('split',next=0,other=cont)
                    inst[loop]['next']=seq(body,loop);cont=loop
                else:
                    for _ in range(maximum-minimum):cont=emit('split',next=seq(body,cont),other=cont)
                for _ in range(minimum):cont=seq(body,cont)
            elif name=='AT':
                names={'AT_BEGINNING':'begin','AT_BEGINNING_STRING':'begin_string','AT_END':'end','AT_END_STRING':'end_string','AT_BOUNDARY':'boundary','AT_NON_BOUNDARY':'not_boundary'}
                cont=emit(names[str(arg)],next=cont)
            else:raise ValueError((name,arg))
        return cont
    start=seq(parsed,emit('match'))
    return dict(start=start,instructions=inst,insensitive=insensitive,multiline=bool(flags&constants.SRE_FLAG_MULTILINE),dotall=bool(flags&constants.SRE_FLAG_DOTALL))

def main():
    source=ROOT/'assets/terminal/detection.json';data=json.loads(source.read_text());programs=[];cache={}
    def program(pattern):
        if pattern not in cache: cache[pattern]=len(programs);programs.append(compile_pattern(pattern))
        return cache[pattern]
    def gate(rule):
        out={}
        for key in ('contains','all','any','not','regex','line_regex'):
            if key not in rule:continue
            value=rule[key]
            if key in ('regex','line_regex'):out[key]=[program(p) for p in value]
            elif key in ('all','any','not'):out[key]=[gate(g) for g in value]
            else:out[key]=value
        return out
    agents=[]
    for name,manifest in data.items():
        rules=[]
        for rule in manifest['rules']:
            item={k:v for k,v in rule.items() if k in ('id','state','priority','region','visible_idle','visible_blocker','visible_working','skip_state_update')}
            item['gate']=gate(rule);rules.append(item)
        agents.append(dict(name=name,aliases=manifest.get('aliases',[]),rules=rules))
    output=dict(source_sha256=hashlib.sha256(source.read_bytes()).hexdigest(),unicode_version=unicodedata.unidata_version,fold=[[cp,fold(cp)] for cp in range(0x110000) if fold(cp)!=cp],agents=agents,programs=programs)
    path=ROOT/'assets/terminal/detection-compiled.json';path.write_text(json.dumps(output,ensure_ascii=False,separators=(',',':'))+'\n')
    print(len(agents),'agents,',len(programs),'regex programs,',path.stat().st_size,'bytes')
if __name__=='__main__':main()
