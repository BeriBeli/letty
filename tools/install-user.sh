#!/bin/bash
# Versioned install from an already extracted package. No system libraries change.
set -euo pipefail
root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)
prefix=${1:-"$HOME/.local/share/letty"}
bin_dir="$HOME/.local/bin"
data_dir=${XDG_DATA_HOME:-"$HOME/.local/share"}
[[ "$data_dir" == /* ]] || data_dir="$HOME/.local/share"
desktop="$data_dir/applications/letty.desktop"
if [[ -e "$bin_dir/letty" && ! -L "$bin_dir/letty" ]]; then echo "$bin_dir/letty is not a symlink; refusing replacement" >&2; exit 1; fi
if [[ -e "$desktop" && ! -L "$desktop" ]]; then echo "$desktop is not a symlink; refusing replacement" >&2; exit 1; fi
if [[ -e "$prefix/letty.desktop" || -L "$prefix/letty.desktop" ]]; then
  if [[ -L "$prefix/letty.desktop" || ! -f "$prefix/letty.desktop" ]] ||
     ! head -n 1 "$prefix/letty.desktop" | grep -qxF '# Generated by Letty install-user.sh'; then
    echo 'Unrecognized letty.desktop in install directory; refusing replacement' >&2; exit 1
  fi
fi
version=$(awk -F'"' '/"package_id"/ {print $4; exit}' "$root/build-info.json")
[[ "$version" =~ ^[A-Za-z0-9._-]+$ ]] || { echo 'Invalid package id' >&2; exit 1; }
mkdir -p -- "$prefix/versions" "$bin_dir" "$data_dir/applications"
# The launcher must also work when a relative custom prefix was supplied.
prefix=$(cd -- "$prefix" && pwd)
target="$prefix/versions/$version"
[[ ! -e "$target" ]] || { echo "Version already exists: $target" >&2; exit 1; }
mkdir -- "$target"
cp -R "$root/." "$target/"
if [[ -e "$prefix/current" && ! -L "$prefix/current" ]]; then echo 'current is not a symlink; refusing replacement' >&2; exit 1; fi
if [[ -L "$prefix/current" ]]; then
  old=$(readlink "$prefix/current")
  ln -s "$old" "$prefix/.previous-new-$$"
  mv -fT "$prefix/.previous-new-$$" "$prefix/previous"
fi
ln -s "versions/$version" "$prefix/.current-new-$$"
mv -fT "$prefix/.current-new-$$" "$prefix/current"
ln -s "$prefix/current/bin/letty" "$bin_dir/.letty-new-$$"
mv -fT "$bin_dir/.letty-new-$$" "$bin_dir/letty"
# Desktop strings and quoted Exec arguments have separate escaping layers.
desktop_string() {
  local value=$1
  value=${value//\\/\\\\}
  value=${value//$'\n'/\\n}
  value=${value//$'\r'/\\r}
  value=${value//$'\t'/\\t}
  printf '%s' "$value"
}
exec_path="$prefix/current/bin/letty"
exec_path=${exec_path//\\/\\\\}
exec_path=${exec_path//\"/\\\"}
exec_path=${exec_path//\$/\\$}
exec_path=${exec_path//\`/\\\`}
exec_path=${exec_path//%/%%}
{
  printf '# Generated by Letty install-user.sh\n[Desktop Entry]\nType=Application\nName=Letty\nComment=Terminal emulator\n'
  printf 'Exec="%s"\n' "$(desktop_string "$exec_path")"
  printf 'Icon=%s\n' "$(desktop_string "$prefix/current/share/icons/hicolor/256x256/apps/letty.png")"
  printf 'Terminal=false\nCategories=System;TerminalEmulator;\nStartupWMClass=Letty\n'
} > "$prefix/.desktop-new-$$"
mv -fT "$prefix/.desktop-new-$$" "$prefix/letty.desktop"
ln -s "$prefix/letty.desktop" "$data_dir/applications/.letty-new-$$"
mv -fT "$data_dir/applications/.letty-new-$$" "$desktop"
if command -v update-desktop-database >/dev/null 2>&1; then
  update-desktop-database "$data_dir/applications" || true
fi
printf 'Installed %s\nRun: %s/letty\nRollback: tools/rollback-user.sh %q\n' "$target" "$bin_dir" "$prefix"
case ":${PATH:-}:" in
  *":$bin_dir:"*) ;;
  *) printf 'Add %s to PATH to run letty by name.\n' "$bin_dir" ;;
esac
